import argparse
import numpy as np
import inspect
import csv
from pathlib import Path
import re
import json

CSV_MAX_ROWS = 0
CSV_MAX_MATCHES = 5
CSV_PATH = 'catalogue/matched_labels_200.csv'
EMBEDDINGS_FILE_NAME = 'embeds.json'
# all-MiniLM-L6-v2 (23M, 384d, CPU-friendly)
