import argparse
import numpy as np
import inspect
import csv
from pathlib import Path
import re
import json

EMBEDDINGS_FILE_NAME = 'embeds.json'
# all-MiniLM-L6-v2 (23M, 384d, CPU-friendly)
# BAAI/bge-small-en-v1.5 (33M, 384d, CPU-friendly)
# NovaSearch/stella_en_400M_v5 (400M)
# BAAI/BGE-M3 (568M, 1024d, GPU-friendly)
# Best Efficiency & High Throughput: BAAI/bge-large-en-v1.5
# Best Overall Performance: Qwen3-Embedding (or NV-Embed-v2): 8B

MODEL_NAME = "all-MiniLM-L6-v2"
# MODEL_NAME = "NovaSearch/stella_en_400M_v5" # needs xformers
# MODEL_NAME = "BAAI/bge-small-en-v1.5" # not as good as all-MiniLM-L6-v2

class SemanticMatcher:

    def run(self):
        parser = argparse.ArgumentParser(
            description="Semantic matcher toolbox",
        )    
        parser.add_argument(
            "action", type=str, help="an action", 
            choices=[a['name'] for a in self.get_actions()]
        )
        
        try:
            args = parser.parse_args()
        except SystemExit as e:
            print(self.get_actions_help())
            raise
        
        action = args.action

        method_name = f'action_{action}'
        method = getattr(self, method_name, None)
        method()       
        
    def get_actions_help(self):
        ret = ['ACTIONS:']

        for action in self.get_actions():
            ret.append(f'  {action["name"]}: {action["desc"]}')

        return '\n'.join(ret)

    def get_actions(self):
        ret = []

        # Get all members that are functions (methods)
        members = inspect.getmembers(self.__class__, predicate=inspect.isfunction)
        
        for name, method in members:
            if name.startswith('action_'):
                docstring = inspect.getdoc(method) or ''
                ret.append({
                    'name': name.replace('action_', ''),
                    'desc': docstring.split('\n')[0],
                })
                
        return ret

    def action_embed_and_match(self):
        '''Embed all and match'''
        self.action_embed_all()
        self.action_match()

    def action_embed_all(self):
        '''Embed catalog and progs'''
        self.action_embed_catalog()
        self.action_embed_progs()

    def action_embed_progs(self):
        '''Embed the summary of the programmes generated by FrameSense'''
        entries = self.read_entries()

        entries = [e for e in entries if e['type'] != 'desc']

        batches_path = Path('./batches')
        for file_path in batches_path.rglob('clip_answers.json'):
            data = json.loads(file_path.read_text())
            summary = data.get('data', {}).get('misc3', {}).get('answer', {}).get('summary', {})

            if summary:
                entries.append({
                    'type': 'desc',
                    'to_embed': summary,
                    'id': str(file_path.parent),
                    'year': data.get('data', {}).get('misc3', {}).get('answer', {}).get('year', {}),
                })

        self.embed_entries(entries)
        self.write_entries(entries)

    def action_embed_catalog(self):
        '''Embed the label of the tapes in the catalog'''
        entries = self.read_entries()

        entries = [e for e in entries if e['type'] != 'label']
        
        cat_path = Path('catalogue/channel-m-all.csv')
        with open(str(cat_path), newline='') as f:
            rows = csv.DictReader(f)
            for row in rows:
                # Heywood fat vox 19/11/07; Plastic bags Chorlton 22/11/07
                labels = row['Label transcription']                
                for label in labels.split(';'):
                    # Heywood fat vox 19/11/07
                    last_date = ''
                    adates = re.findall(r'\b\d{1,2}/\d{1,2}/\d{1,2}\b', label)
                    if adates:
                        for adate in adates:
                            last_date = adate
                            label = label.replace(adate, '')
                    
                    label = label.strip()

                    if label:                        
                        entries.append({
                            'type': 'label',
                            'to_embed': label,
                            'id': row['Date Hard Drive returned to BFI'].replace('.mkv', ''),
                            'date': last_date,
                        })

        self.embed_entries(entries)
        self.write_entries(entries)

    def embed_entries(self, entries):
        from sentence_transformers import SentenceTransformer
        model = SentenceTransformer(MODEL_NAME, trust_remote_code=True)

        for entry in entries:
            if entry.get('embed', None) is None:
                entry['embed'] = model.encode([entry['to_embed']], normalize_embeddings=True)[0].astype(float).tolist()

    def read_entries(self):
        ret = []
        entries_path = Path(EMBEDDINGS_FILE_NAME)
        if entries_path.exists():
            ret = json.loads(entries_path.read_text())
        return ret

    def write_entries(self, entries):
        entries_path = Path(EMBEDDINGS_FILE_NAME)
        entries_path.write_text(json.dumps(entries, indent=2))

    def action_match(self):
        '''Match generated programme summaries with tape labels'''
        entries = self.read_entries()

        labels = [e for e in entries if e['type'] == 'label']
        labels_embeds = np.array([l['embed'] for l in labels], dtype=np.float32)

        correct_filenames_label = self.read_ground_truth()

        last_file = ''
        stats = {
            'files': 0,
            'match-1': 0,
            'match-10': 0
        }
        has_confirmed_match = False
        for entry in entries:
            if entry['type'] != 'desc':
                continue

            # batches/N_6970744_01of01_Johnny Marr/00.00.33-166-full-sub-prog -> N_6970744_01of01
            filename = '_'.join(entry['id'].split('/')[1].split('_')[:3])
            correct_label = correct_filenames_label[filename]
            sep = '-'
            if last_file != filename:
                sep = '='
                stats['files'] += 1
                has_confirmed_match = False
            print(sep * 75)
            print('prog:', entry['id'])
            print('desc:', entry['to_embed'])
            print('true:', correct_label)

            # Cosine similarity (equivalent to dot product when normalised)
            scores = labels_embeds @ np.array(entry['embed'], dtype=np.float32)

            # Top 5
            top5_idx = np.argsort(scores)[::-1][:10]
            for rank, i in enumerate(top5_idx, 1):
                status = '    '
                if self.normalise_label(labels[i]['to_embed']) == self.normalise_label(correct_label):
                    status = 'TRUE'
                    if not has_confirmed_match:
                        has_confirmed_match = True
                        # TODO: should only +1 per file, not per prog
                        stats['match-10'] += 1
                        if rank == 1:
                            stats['match-1'] += 1
                print(f"  {status} {rank}. {scores[i]*100:.1f}% similar to '{labels[i]['to_embed']}' (misattributed to {labels[i]['id']})")
            
            last_file = filename

        print(f'\n{stats["files"]} files; {stats["match-10"]} confirmed top-10 matches; {stats["match-1"]} confirmed top-1 matches; model: {MODEL_NAME}')

    def normalise_label(self, label):
        ret = re.sub(r'\W', '', label).lower()
        return ret

    def action_test(self):
        self.read_ground_truth()

    def read_ground_truth(self):
        '''
        reads and returns the correct mapping between filename and label 
        from channel-m-replay.csv.

        returns {
            'N_6989390_01of01': '[BAD EGG SMELL IN RAMSBOTTOM]',
            ...
        }
        '''
        ret = {}
        replay_path = Path('catalogue/channel-m-replay.csv')
        with open(str(replay_path), newline='') as f:
            rows = csv.DictReader(f)
            for row in rows:
                ret[row['BFI filename'].replace('.mp4', '')] = row['title']

        return ret
            
if __name__ == "__main__":
    matcher = SemanticMatcher()
    matcher.run()
